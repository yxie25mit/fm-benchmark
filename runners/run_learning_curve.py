"""
Learning-curve driver: trains each method on nested training-size fractions.

Reuses the exact scheduler from run_phase (Job + run_jobs_with_retry: GPU-slot pool,
done.flag resume, OOM-halving retry). Fractions are pseudo-protocols
(<base>__f<FFF>) whose split dirs are pre-generated by
scripts/make_learning_curve_subsets.py, so no trainer code changes are needed.

f100 is NOT run here — it is the existing `default` phase (default HP) or `hp_final`
(tuned HP) result; aggregation pulls that point in separately.

Output layout:
  results/<method>/<ds>/learning_curve/<base_protocol>/<ftag>/seed<S>_em<E>/{metrics.json,done.flag,...}

Fast preview (default): 1 seed, 1 ensemble member, fixed default HP.
"""
import argparse
import sys
from pathlib import Path

PIPELINE = Path("/data/rbg/users/yxie25/molclr_chemprop/clean_pipeline_v1")
sys.path.insert(0, str(PIPELINE / "runners"))
sys.path.insert(0, str(PIPELINE / "methods"))

from run_phase import Job, run_jobs_with_retry  # noqa: E402
from configs import METHODS  # noqa: E402

ALL_METHODS = ["chemprop2", "chemprop2_nofp", "molclr", "chemeleon", "molfcl", "motil", "molformer"]
DEFAULT_FRACTIONS = ["f005", "f010", "f020", "f040", "f070"]  # f100 = existing default/hp_final


def build_jobs(methods, datasets, base_protocols, fractions, seeds, ensemble, epochs, gpus):
    jobs = []
    index = 0
    for method in methods:
        for dataset in datasets:
            for base in base_protocols:
                for ftag in fractions:
                    pseudo_protocol = f"{base}__{ftag}"
                    split_dir = PIPELINE / "splits" / dataset / f"{pseudo_protocol}_seed{seeds[0]}"
                    if not split_dir.exists():
                        print(f"  SKIP missing split: {split_dir} (run make_learning_curve_subsets.py)")
                        continue
                    for seed in seeds:
                        for member in range(ensemble):
                            out_dir = (PIPELINE / "results" / method / dataset / "learning_curve"
                                       / base / ftag / f"seed{seed}_em{member}")
                            jobs.append(Job(method, dataset, pseudo_protocol, seed,
                                            "default", "default", member, epochs, out_dir,
                                            gpus[index % len(gpus)]))
                            index += 1
    return jobs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--methods", nargs="+", default=ALL_METHODS)
    parser.add_argument("--datasets", nargs="+", default=["bace", "esol"])
    parser.add_argument("--protocols", nargs="+", default=["v1_preshuffle", "v2_astartes"])
    parser.add_argument("--fractions", nargs="+", default=DEFAULT_FRACTIONS)
    parser.add_argument("--seeds", nargs="+", type=int, default=[0])
    parser.add_argument("--ensemble", type=int, default=1, help="ensemble members per point")
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--gpus", default="0", help="comma-separated, e.g. '2,6,7'")
    parser.add_argument("--jobs-per-gpu", type=int, default=2)
    parser.add_argument("--force-methods", nargs="*", default=[],
                        help="clear+re-run cells ONLY for these methods (e.g. chemprop2 chemeleon), "
                             "leaving other methods' completed cells intact for resume")
    args = parser.parse_args()

    gpus = [g.strip() for g in args.gpus.split(",") if g.strip() != ""]
    jobs = build_jobs(args.methods, args.datasets, args.protocols, args.fractions,
                      args.seeds, args.ensemble, args.epochs, gpus)

    if args.force_methods:
        import shutil
        cleared = 0
        for job in jobs:
            if job.method in args.force_methods and job.out_dir.exists():
                shutil.rmtree(job.out_dir, ignore_errors=True)
                cleared += 1
        print(f"--force-methods {args.force_methods}: cleared {cleared} cell dirs")

    todo = [j for j in jobs if not (j.out_dir / "done.flag").exists()]
    print(f"learning-curve: {len(jobs)} cells total, {len(jobs) - len(todo)} already done, "
          f"{len(todo)} to run | gpus={gpus} jobs_per_gpu={args.jobs_per_gpu}")
    if not todo:
        print("nothing to do")
        return

    results = run_jobs_with_retry(jobs, gpus, args.jobs_per_gpu)
    print(f"\nDONE: ok={len(results['ok'])} done={len(results['done'])} "
          f"fail={len(results['fail'])} oom={len(results['oom'])} timeout={len(results['timeout'])}")
    for status in ("fail", "oom", "timeout"):
        for job, _ in results[status][:10]:
            print(f"  {status}: {job}")


if __name__ == "__main__":
    main()
